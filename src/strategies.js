const PA_GROUP_ORDER = ['Entry', 'Filters', 'Risk', 'Exit'];
const PA_NOTE_FOLDER = { id: 'nbf_strategies', name: 'คู่มือ Strategy' };

function paPlaybook(def, s, t) {
  return {
    id: def.id, name: def.name, description: def.description, status: 'Active', color: def.color,
    relevantTagIds: [],
    ruleGroups: PA_GROUP_ORDER.map(g => ({ id: `rg_${def.id.slice(3)}_${g.toLowerCase()}`, name: g, items: (def.rules[g] || []).map((r, i) => ({ id: `${def.id.slice(3, 6)}_${g.slice(0, 2).toLowerCase()}${i + 1}`, label: r[0] })) })),
    notes: [], createdAt: t, source: 'pa-top6',
  };
}
function paNoteHTML(def) {
  const e = v => esc(v);
  return `<h2>แนวคิด</h2><p>${e(def.concept)}</p><p><b>สภาพตลาด:</b> ${e(def.market)}<br><b>กรอบเวลา:</b> ${e(def.tf)}<br><b>Session:</b> ${e(def.session)}</p>`
    + PA_GROUP_ORDER.map(g => `<h2>${g}</h2><table><thead><tr><th>กฎ</th><th>วิธีใช้</th></tr></thead><tbody>${(def.rules[g] || []).map(([r, h]) => `<tr><td>${e(r)}</td><td>${e(h)}</td></tr>`).join('')}</tbody></table>`).join('')
    + `<h2>Invalidation</h2><p>${e(def.invalidation)}</p>`;
}
function paNote(def, t) { return { id: 'note_' + def.id, folderId: PA_NOTE_FOLDER.id, title: `${def.name} — คู่มือ Strategy`, strategyIds: [def.id], html: paNoteHTML(def), createdAt: t, updatedAt: t }; }

/* add the Top 6 to a workspace (seed, demo, or the "add defaults" action); skips ones already present */
function addPaStrategies(s, t = now()) {
  let added = 0;
  if (!(s.notebookFolders ||= []).some(f => f.id === PA_NOTE_FOLDER.id)) s.notebookFolders.push({ ...PA_NOTE_FOLDER, createdAt: t });
  for (const def of PA_STRATEGIES) {
    if ((s.playbooks ||= []).some(p => p.id === def.id)) continue;
    s.playbooks.push(paPlaybook(def, s, t)); added++;
    if (!(s.notebooks ||= []).some(n => n.id === 'note_' + def.id)) s.notebooks.push(paNote(def, t));
  }
  return added;
}
